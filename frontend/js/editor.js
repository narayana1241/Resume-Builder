async function loadWorkspaceData() {
    try {
        const localTemplateOverride = localStorage.getItem(`resume_template_id_${resume_id}`);
        const sessionTemplateOverride = sessionStorage.getItem("temp_template_id");
        activeTemplateId = localTemplateOverride ? Number(localTemplateOverride) : (sessionTemplateOverride ? Number(sessionTemplateOverride) : 1);

        // 1. Fetch templates metadata
        try {
            const templatesRes = await fetch(`${API_BASE_URL}/api/templates`);
            const templatesJson = await templatesRes.json();
            if (templatesJson.success && templatesJson.data) {
                templatesList = Array.isArray(templatesJson.data) ? templatesJson.data : (templatesJson.data.data || []);
            }
        } catch (e) {
            console.warn("Could not fetch templates list, using fallback.");
        }

        // 2. Check if resume_id exists in URL/DB
        const urlParams = new URLSearchParams(window.location.search);
        const urlResumeId = urlParams.get("resume_id") || localStorage.getItem("resume_id");

        if (urlResumeId && urlResumeId !== "null" && urlResumeId !== "undefined" && !urlParams.get("source")) {
            resume_id = urlResumeId;
            try {
                const response = await fetch(`${API_BASE_URL}/api/resume/editor/${resume_id}?user_id=${user_id}`);
                const result = await response.json();

                if (result.success && result.data) {
                    const d = result.data;
                    previewData = {
                        user_id: d.user_id || user_id || 1,
                        resume_id: d.resume_id || resume_id,
                        template_id: d.template_id || activeTemplateId,
                        resume_title: d.resume_title || "My Resume",
                        upload_confidence: d.upload_confidence || 100,
                        is_draft: d.is_draft !== undefined ? d.is_draft : true,
                        personal_details: d.personal && Object.keys(d.personal).length > 0 ? [d.personal] : [{}],
                        education: d.education || [],
                        experience: d.experience || [],
                        skills: d.skills || [],
                        projects: d.projects || [],
                        certifications: d.certifications || [],
                        languages: d.languages || [],
                        custom_sections: d.custom_sections || [],
                        section_status: d.section_status || {}
                    };

                    const badge = document.getElementById("draftStatusBadge");
                    if (badge) {
                        badge.innerHTML = `<i class="fa-solid fa-cloud-check"></i> ✓ Saved to Database`;
                        badge.style.color = "#10b981";
                    }
                }
            } catch (fetchErr) {
                console.warn("Could not fetch DB resume details, using session fallback:", fetchErr);
            }
        }

        if (!previewData) {
            // Temporary Session Draft from sessionStorage
            const tempDraftStr = sessionStorage.getItem("temp_resume_parsed_data");
            if (tempDraftStr) {
                console.log("Loading temporary upload draft from sessionStorage into editor...");
                const parsedObj = JSON.parse(tempDraftStr);
                previewData = {
                    user_id: user_id || 1,
                    resume_id: null,
                    template_id: activeTemplateId,
                    resume_title: parsedObj.resume_title || "Uploaded Resume Draft",
                    upload_confidence: parsedObj.upload_confidence || 95,
                    personal_details: [parsedObj.personal || {}],
                    education: parsedObj.education || [],
                    experience: parsedObj.experience || [],
                    skills: parsedObj.skills || [],
                    projects: parsedObj.projects || [],
                    certifications: parsedObj.certifications || [],
                    languages: parsedObj.languages || [],
                    custom_sections: parsedObj.custom_sections || []
                };
            } else {
                previewData = {
                    user_id: user_id || 1,
                    resume_id: null,
                    template_id: activeTemplateId,
                    resume_title: "My Resume Draft",
                    personal_details: [{}],
                    education: [],
                    experience: [],
                    skills: [],
                    projects: [],
                    certifications: [],
                    languages: [],
                    custom_sections: []
                };
            }

            const badge = document.getElementById("draftStatusBadge");
            if (badge) {
                badge.innerHTML = `<i class="fa-solid fa-clock"></i> Unsaved Session Draft`;
                badge.style.color = "#f59e0b";
            }
        }

        // Set navbar title
        const titleBadge = document.getElementById("resumeTitleBadge");
        if (titleBadge && previewData.resume_title) {
            titleBadge.textContent = previewData.resume_title;
        }

        if (previewData.template_id && !localTemplateOverride) {
            activeTemplateId = Number(previewData.template_id);
        }

        // Pre-fill form sections
        prefillContactsForm();
        renderEducationList();
        renderExperienceList();
        renderSkillsList();
        renderProjectsList();
        renderCertificationsList();
        renderCustomSectionsList();

        // Render Live Preview
        await renderLivePreview();

    } catch (err) {
        console.error("Error loading workspace details:", err);
    }
}

