let isDirty = false;
let isAutoSaveRunning = false;

function markDirty() {
    isDirty = true;
    const badge = document.getElementById("draftStatusBadge");
    if (badge) {
        if (!resume_id) {
            badge.innerHTML = `<i class="fa-solid fa-clock"></i> Unsaved Session Draft`;
            badge.style.color = "#f59e0b";
        } else {
            badge.innerHTML = `<i class="fa-solid fa-spinner fa-spin"></i> Saving draft...`;
            badge.style.color = "#f59e0b";
        }
    }
}

async function triggerAutoSave() {
    // Only auto-save to DB if a resume_id has been generated by explicit Save Resume
    if (!isDirty || isAutoSaveRunning || !resume_id) return;
    isAutoSaveRunning = true;
    try {
        const payload = {
            user_id: user_id || 1,
            resume_id: resume_id,
            resume_name: (previewData && previewData.resume_title) ? previewData.resume_title : "Untitled Resume",
            template_id: activeTemplateId || 1,
            is_draft: true,
            resume_json: previewData
        };
        await fetch(`${API_BASE_URL}/api/resume/save-json`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(payload)
        });
        isDirty = false;
        const badge = document.getElementById("draftStatusBadge");
        if (badge) {
            badge.innerHTML = `<i class="fa-solid fa-cloud-check"></i> ✓ Saved to Database`;
            badge.style.color = "#10b981";
        }
    } catch (err) {
        console.error("Auto-save error:", err);
    } finally {
        isAutoSaveRunning = false;
    }
}

setInterval(triggerAutoSave, 3000);

// Explicit Save Resume Handler (Creates resume_id & saves custom sections in PostgreSQL)
async function saveResumeToDatabase() {
    const saveBtn = document.getElementById("btnSaveResume");
    if (saveBtn) {
        saveBtn.classList.add("disabled");
        saveBtn.innerHTML = `<i class="fa-solid fa-spinner fa-spin"></i> Saving to Database...`;
    }

    try {
        const uploadPayload = {
            user_id: user_id || 1,
            resume_id: resume_id || null,
            resume_title: (previewData && previewData.resume_title) ? previewData.resume_title : "My Resume",
            template_id: activeTemplateId || 1,
            upload_confidence: (previewData && previewData.upload_confidence) ? previewData.upload_confidence : 100,
            is_draft: false,
            personal: (previewData && previewData.personal_details && previewData.personal_details[0]) ? previewData.personal_details[0] : {},
            education: (previewData && previewData.education) ? previewData.education : [],
            experience: (previewData && previewData.experience) ? previewData.experience : [],
            skills: (previewData && previewData.skills) ? previewData.skills : [],
            projects: (previewData && previewData.projects) ? previewData.projects : [],
            certifications: (previewData && previewData.certifications) ? previewData.certifications : [],
            languages: (previewData && previewData.languages) ? previewData.languages : [],
            custom_sections: (previewData && previewData.custom_sections) ? previewData.custom_sections : []
        };

        console.log("Saving full resume payload to PostgreSQL database...", uploadPayload);
        const res = await fetch(`${API_BASE_URL}/api/resume/save-full-upload`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(uploadPayload)
        });

        const saveResult = await res.json();
        if (saveResult.success && (saveResult.resume_id || saveResult.ref_id)) {
            const newResumeId = saveResult.resume_id || saveResult.ref_id;
            resume_id = newResumeId;

            localStorage.setItem("resume_id", newResumeId);
            localStorage.setItem(`resume_template_id_${newResumeId}`, activeTemplateId);
            sessionStorage.removeItem("temp_resume_parsed_data");

            // Update URL cleanly without reloading
            window.history.replaceState(null, "", `editor.html?resume_id=${newResumeId}`);

            const badge = document.getElementById("draftStatusBadge");
            if (badge) {
                badge.innerHTML = `<i class="fa-solid fa-cloud-check"></i> ✓ Saved to Database`;
                badge.style.color = "#10b981";
            }

            alert("Resume saved successfully to PostgreSQL database!");
        } else {
            alert(saveResult.message || "Failed to save resume. Please try again.");
        }
    } catch (err) {
        console.error("Save Resume Error:", err);
        alert("An error occurred while saving resume to database.");
    } finally {
        if (saveBtn) {
            saveBtn.classList.remove("disabled");
            saveBtn.innerHTML = `<i class="fa-solid fa-cloud-arrow-up"></i> Save Resume`;
        }
    }
}

