const customSectionForm = document.getElementById("customSectionForm");
if (customSectionForm) {
    customSectionForm.addEventListener("submit", function(e) {
        e.preventDefault();
        const titleInput = document.getElementById("custom_section_title");
        const itemInput = document.getElementById("custom_section_item");
        if (!titleInput || !itemInput) return;

        const title = titleInput.value.trim();
        const item = itemInput.value.trim();
        if (!title || !item) return;

        if (!previewData.custom_sections) previewData.custom_sections = [];

        let existing = previewData.custom_sections.find(c => c.section_title.toLowerCase() === title.toLowerCase());
        if (existing) {
            if (!Array.isArray(existing.section_data)) existing.section_data = [existing.section_data];
            existing.section_data.push(item);
        } else {
            previewData.custom_sections.push({
                section_title: title,
                section_data: [item],
                display_order: previewData.custom_sections.length + 1
            });
        }

        titleInput.value = "";
        itemInput.value = "";

        renderCustomSectionsList();
        renderLivePreview();
        markDirty();
    });
}

